const BY_ID = new Map(VERSES.map((v) => [v.id, v]));

export function getVerse(id: string): Verse | undefined {
  return BY_ID.get(id);
}

/** The bank in `order`, ascending — the curriculum sequence. */
export function versesInOrder(): Verse[] {
  return [...VERSES].sort((a, b) => a.order - b.order);
}

/** The bank in canonical Bible order (Genesis through Revelation). */
export function versesInCanonOrder(): Verse[] {
  return [...VERSES];
}
